def strings(lang, engine=None):
    """S[lang] with the engine's overrides applied (Oracle / engine None: S[lang] itself)."""
    over = ENGINE_S.get(engine or "oracle", {}).get(lang)
    if not over:
        return S[lang]
    merged = dict(S[lang])
    for key, value in over.items():
        merged[key] = {**S[lang][key], **value} if isinstance(value, dict) else value
    return merged
